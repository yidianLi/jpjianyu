"""把 wms.sql(MySQL 5.6 方言)转换为国产库 DDL(达梦 DM / PG 族:金仓 Kingbase/瀚高 HGDB).

best-effort 转换,覆盖本项目实际用到的 MySQL 专有写法:
  - 反引号标识符、INT(11)/TINYINT/BIGINT、DATETIME
  - AUTO_INCREMENT、ON UPDATE CURRENT_TIMESTAMP
  - 尾部 ENGINE=InnoDB DEFAULT CHARSET=... COMMENT='...'
  - 行内 KEY/UNIQUE KEY/INDEX 索引 -> 拆成独立 CREATE INDEX
  - 列/表 COMMENT '...' -> 移除(建议后续用 COMMENT ON 补)
转换结果务必用目标库实测;达梦/金仓官方 DTS 迁移工具可作二次校验。

用法: python gen_portable_ddl.py            # 生成 wms_pg.sql 与 wms_dm.sql
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def _conv_type(line, target):
    line = line.replace("`", "")
    line = re.sub(r"\bINT\(\d+\)", "INTEGER", line)
    line = re.sub(r"\bBIGINT\(\d+\)", "BIGINT", line)
    line = re.sub(r"\bSMALLINT\(\d+\)", "SMALLINT", line)
    line = re.sub(r"\bDATETIME\b", "TIMESTAMP", line)
    if target == "pg":
        line = re.sub(r"\bTINYINT\b", "SMALLINT", line)
        line = re.sub(r"\bAUTO_INCREMENT\b",
                      "GENERATED BY DEFAULT AS IDENTITY", line)
    else:  # dm
        line = re.sub(r"\bAUTO_INCREMENT\b", "IDENTITY(1,1)", line)
    line = re.sub(r"\bON UPDATE CURRENT_TIMESTAMP\b", "", line)
    line = re.sub(r"\bON UPDATE NOW\(\)", "", line)
    line = re.sub(r"COMMENT\s+'([^']*)'", "", line)
    line = re.sub(r"\s+,", ",", line)
    line = re.sub(r"\s{2,}", " ", line)
    return line.rstrip()


def _split_statements(text):
    stmts, buf = [], []
    for ln in text.splitlines():
        buf.append(ln)
        if ln.rstrip().endswith(";"):
            stmts.append("\n".join(buf))
            buf = []
    if buf:
        stmts.append("\n".join(buf))
    return stmts


KEY_RE = re.compile(r"^\s*(?:UNIQUE\s+)?(?:KEY|INDEX)\s+`?(\w+)`?\s*\(([^)]*)\)\s*,?\s*$",
                    re.I)


def convert(sql, target):
    out = []
    for stmt in _split_statements(sql):
        idx = re.search(r"CREATE\s+TABLE", stmt, re.I)
        if not idx:
            out.append(stmt)
            continue
        pre = stmt[:idx.start()]
        block = stmt[idx.start():]
        m = re.search(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?",
                      block, re.I)
        table = m.group(1) if m else "t"
        lines = block.splitlines()
        body, indexes = [], []
        for ln in lines:
            km = KEY_RE.match(ln)
            if km and "PRIMARY" not in ln.upper():
                uniq = "UNIQUE" if ln.strip().upper().startswith("UNIQUE") else ""
                indexes.append("CREATE %sINDEX %s ON %s (%s);"
                               % (uniq + " " if uniq else "",
                                  km.group(1), table,
                                  km.group(2).replace("`", "")))
                continue
            body.append(_conv_type(ln, target))
        tail_i = len(body) - 1
        for i in range(len(body) - 1, -1, -1):
            if body[i].strip().startswith(")"):
                tail_i = i
                break
        body[tail_i] = ");"
        j = tail_i - 1
        while j >= 0 and body[j].strip() == "":
            j -= 1
        if j >= 0:
            body[j] = body[j].rstrip().rstrip(",")
        out.append(pre + "\n".join(body))
        out.extend(indexes)
    return "\n\n".join(out) + "\n"


def main():
    src = os.path.join(HERE, "wms.sql")
    with open(src, encoding="utf-8") as f:
        sql = f.read()
    for target, name, banner in [
        ("pg", "wms_pg.sql",
         "-- 由 gen_portable_ddl.py 生成(金仓 Kingbase/瀚高 HGDB/GaussDB, PG 族)\n"
         "-- 部署前请用目标库执行校验;建议配合厂商 DTS 迁移工具。\n"),
        ("dm", "wms_dm.sql",
         "-- 由 gen_portable_ddl.py 生成(达梦 DM8)\n"
         "-- 部署前请用目标库执行校验;建议配合达梦 DTS 迁移工具。\n"),
    ]:
        dst = os.path.join(HERE, name)
        with open(dst, "w", encoding="utf-8") as f:
            f.write(banner + convert(sql, target))
        print("wrote", name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
